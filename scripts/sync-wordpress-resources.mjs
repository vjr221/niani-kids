import { writeFileSync } from 'node:fs';

const API = 'https://nianikids.com/wp-json/wp/v2/posts';
const response = await fetch(`${API}?status=publish&per_page=20&page=1&orderby=date&order=desc&_fields=id,date,link,slug,title,excerpt`, {
  headers: { 'User-Agent': 'NianiKids-ContentSync/1.0' },
  signal: AbortSignal.timeout(20000),
});
if (!response.ok) throw new Error(`WordPress REST API returned HTTP ${response.status}`);
const posts = await response.json();
if (!Array.isArray(posts)) throw new Error('Unexpected WordPress REST response');
const clean = (value = '') => String(value).replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&#8217;/g, '’').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
const resources = posts
  .filter((post) => post?.id && post?.link && post?.slug && post?.title?.rendered)
  .map((post) => ({
    id: `wp-post-${post.id}`,
    icon: '📚',
    titleFr: clean(post.title.rendered),
    titleWo: clean(post.title.rendered),
    descriptionFr: clean(post.excerpt?.rendered || 'Une nouvelle ressource Niani Kids à découvrir en famille.').slice(0, 220),
    descriptionWo: 'Jumtukaay bu bees Niani Kids. Xool ko ak sa njaboot.',
    url: post.link,
    publishedAt: post.date,
    source: 'wordpress',
  }));
if (resources.length === 0) throw new Error('No published WordPress posts returned; refusing to overwrite the app catalogue');
const output = `/** Generated by scripts/sync-wordpress-resources.mjs. Do not edit manually. */\nexport const generatedSiteResources = ${JSON.stringify(resources, null, 2)} as const;\n`;
writeFileSync(new URL('../src/generatedSiteResources.ts', import.meta.url), output);
console.log(`Synced ${resources.length} published WordPress articles.`);
